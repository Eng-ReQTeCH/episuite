import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium, browserOptions, waitForCondition } from './browser-runtime.mjs';
import { createApp } from '../server.mjs';
import { initialState, taskInput } from '../public/domain.js';

const directory = await mkdtemp(path.join(tmpdir(), 'episuite-productivity-browser-'));
const screenshots = fileURLToPath(new URL('../test-results/', import.meta.url));
let app, browser;
try {
  const fixture = initialState();
  fixture.onboarding = { status: 'complete', step: 7 };
  Object.assign(fixture.settings, { sound: false, quietFocus: true, showStreaks: false });
  const task = taskInput({ title: '<b>Draft & review</b>', lane: 'today', nextAction: 'Open the draft' });
  const habit = taskInput({ title: 'Read daily', repeat: 'daily', habitCue: 'My morning coffee', habitMinimum: 'One paragraph' });
  fixture.tasks.push(task, habit);
  await writeFile(path.join(directory, 'episuite.json'), JSON.stringify(fixture));
  app = await createApp({ dataDir: directory, backgroundInterval: 0 });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  const base = 'http://127.0.0.1:' + app.server.address().port;
  browser = await chromium.launch(browserOptions);
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(10000);
  const save = async () => {
    await page.locator('#dialog [type="submit"]').click();
    await page.locator('#dialog').waitFor({ state: 'hidden' });
  };
  await page.goto(base);
  await page.getByRole('button', { name: 'Choose an outcome', exact: true }).click();
  await page.locator('#f-taskId').selectOption(task.id);
  await page.locator('#f-outcome').fill('Finish the introduction');
  await save();
  assert.ok((await page.locator('#main').innerText()).includes('Finish the introduction'));
  await page.getByRole('button', { name: 'Start 2-minute burst →', exact: true }).click();
  await page.getByRole('button', { name: 'Save where I am', exact: true }).click();
  await page.locator('#f-title').fill('Write the first sentence');
  await save();
  await page.getByText('Write the first sentence', { exact: true }).waitFor();
  const other = await context.newPage();
  await other.goto(base);
  await other.getByRole('button', { name: 'Return to my session →', exact: true }).click();
  await other.getByText('Write the first sentence', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Take a short break', exact: true }).click();
  await waitForCondition(() => app.getState().timer?.mode === 'short');
  assert.equal(app.getState().timer.mode, 'short');
  await page.getByRole('button', { name: 'Show workspace', exact: true }).click();
  await page.locator('.phone-dock [data-id="tasks"]').click();
  const row = page.locator('.task-row').filter({ hasText: '<b>Draft & review</b>' });
  await row.locator('.task-more summary').click();
  await row.locator('[data-action="task-history"]').click();
  assert.equal(await page.locator('#dialog-title').innerText(), '<b>Draft & review</b>');
  assert.equal(await page.locator('#dialog-title b').count(), 0);
  await page.locator('#dialog [data-action="close-dialog"]').click();
  await page.locator('[data-action="task-tab"][data-id="habits"]').click();
  await page.getByRole('button', { name: 'Log minimum version', exact: true }).click();
  await waitForCondition(() => Object.keys(app.getState().tasks.find(task => task.id === habit.id).history).length > 0);
  assert.equal(app.getState().tasks.find(item => item.id === habit.id).history[Object.keys(app.getState().tasks.find(item => item.id === habit.id).history)[0]].length, 1);
  await page.goto(base + '/#progress');
  await page.getByRole('button', { name: 'Write this week’s review', exact: true }).click();
  await page.locator('#f-outcome').fill('An introduction drafted');
  await page.locator('#f-adjustment').fill('Keep speech-free reading');
  await save();
  await page.getByRole('button', { name: 'Private focus experiments', exact: true }).click();
  await page.getByRole('button', { name: 'Log an audio trial', exact: true }).click();
  await page.locator('#f-condition').selectOption('quiet');
  await page.locator('#f-friction').selectOption('2');
  await save();
  await page.getByRole('button', { name: 'Private focus experiments', exact: true }).click();
  const summary = page.locator('.productivity-table tbody tr').filter({ hasText: 'Speech-free' });
  assert.equal(await summary.locator('td').first().innerText(), '1');
  assert.equal(Object.hasOwn(await (await fetch(base + '/api/export')).json(), 'experiments'), false);
  await page.locator('#dialog [data-action="close-dialog"]').click();
  await page.goto(base + '/#now');
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  await context.setOffline(true);
  const capture = async (target, text) => {
    // Keyboard activation avoids background-tab animation-frame throttling during concurrent capture.
    await target.locator('[data-action="quick-capture"]').first().press('Enter');
    await target.locator('#quick-capture').fill(text);
    await target.locator('#dialog [type="submit"]').click();
    await target.locator('#dialog').waitFor({ state: 'hidden' });
  };
  await Promise.all([capture(page, 'First offline note'), capture(other, 'Second offline note')]);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.body.textContent.includes('pending'));
  await context.setOffline(false);
  await Promise.all([page, other].map(target => target.evaluate(() => window.dispatchEvent(new Event('online')))));
  await waitForCondition(() => ['First offline note', 'Second offline note'].every(text =>
    app.getState().notes.filter(note => note.text === text).length === 1));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Phone layout fits');
  await mkdir(screenshots, { recursive: true });
  await page.screenshot({ path: path.join(screenshots, 'productivity-now-phone.png'), fullPage: true });
  await page.goto(base + '/#progress');
  await page.screenshot({ path: path.join(screenshots, 'productivity-progress-phone.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base + '/#now');
  await page.screenshot({ path: path.join(screenshots, 'productivity-now-desktop.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Productivity browser checks passed');
} finally {
  await browser?.close();
  await app?.close();
  assert.ok(path.resolve(directory).startsWith(path.resolve(tmpdir()) + path.sep + 'episuite-productivity-browser-'));
  await rm(directory, { recursive: true, force: true });
}
