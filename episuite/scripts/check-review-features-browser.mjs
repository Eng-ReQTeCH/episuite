import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium, browserOptions, waitForCondition } from './browser-runtime.mjs';
import { createApp } from '../server.mjs';
import { initialState, taskInput, dateKey, addDays, isDue } from '../public/domain.js';
import { bookInput, logReading } from '../public/books-domain.js';

const directory = await mkdtemp(path.join(tmpdir(), 'episuite-review-browser-'));
let app, browser;
try {
  const state = initialState(), today = dateKey();
  state.onboarding = { status: 'complete', step: 7 };
  state.settings.sound = false;
  const reading = taskInput({ title: 'Reading', repeat: 'interval_0.5', minimumGapMinutes: 0 });
  const offlineTask = taskInput({ title: 'A task to check off offline' });
  state.tasks.push(reading, offlineTask);
  state.reading.policy = 'session';
  const book = bookInput({ title: 'Atomic Habits', author: 'James Clear', coverId: 12539702, totalPages: 200 });
  state.reading.books.push(book);
  for (let index = 0; index < 14; index++) logReading(state, book, { page: index + 1, eventId: 'old-' + index, expectedVersion: book.editVersion }, addDays(today, index - 15));
  state.reading.books.push(bookInput({ title: 'A past book', author: 'Past author', status: 'finished', finishedDate: '2024-03-15' }));
  await writeFile(path.join(directory, 'episuite.json'), JSON.stringify(state));
  app = await createApp({ dataDir: directory, backgroundInterval: 0, bookFetch: async () => ({
    ok: true, json: async () => ({ docs: [{ key: '/works/OL30048054W', title: 'Companion Workbook: Atomic Habits', author_name: ['Julie Ann Price'], cover_i: 15095106 }] })
  }) });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  const base = 'http://127.0.0.1:' + app.server.address().port;
  browser = await chromium.launch(browserOptions);
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(10000);
  const save = async () => {
    await page.locator('#dialog [type="submit"]').click();
    await page.locator('#dialog').waitFor({ state: 'hidden' }).catch(async error => { throw new Error(error.message + '\n' + await page.locator('#dialog').innerText() + '\n' + await page.locator('#toast').innerText()); });
  };
  const close = () => page.locator('#dialog [data-action="close-dialog"]').click();
  await page.goto(base + '/#life');
  await page.locator('[data-action="book-details"]').first().click();
  await page.getByRole('button', { name: 'Older sessions', exact: true }).click();
  assert.ok((await page.locator('.book-log-history').innerText()).includes(addDays(today, -15)));
  await page.getByRole('button', { name: 'Previous sessions', exact: true }).click();
  await page.getByRole('button', { name: 'Edit session', exact: true }).first().click();
  await page.locator('#f-page').fill('13');
  await page.locator('#f-from').fill('11');
  await save();
  assert.equal(app.getState().reading.books[0].currentPage, 13);

  await page.locator('[data-action="book-log"]').first().click();
  await page.locator('#f-from').fill('13');
  await page.locator('#f-page').fill('20');
  await page.locator('#f-date').fill(addDays(today, -1));
  await save();
  assert.equal(app.getState().reading.books[0].logs.at(-1).date, addDays(today, -1));
  await page.locator('[data-action="book-details"]').first().click();
  await page.getByRole('button', { name: 'Edit book', exact: true }).click();
  await page.getByRole('button', { name: 'Change cover / book match', exact: true }).click();
  await page.locator('[data-form="book-search"] [type="submit"]').click();
  await page.locator('.book-result').first().click();
  await save();
  assert.equal(app.getState().reading.books[0].coverId, 15095106);
  assert.equal(app.getState().reading.books[0].logs.length, 15);

  await page.getByRole('button', { name: 'All books', exact: true }).click();
  await page.locator('#book-library-query').fill('Past author');
  assert.equal(await page.locator('#dialog .book-card').count(), 1);
  await page.locator('#book-library-query').fill('');
  await page.locator('[name="libraryShelf"]').selectOption('finished');
  assert.equal(await page.locator('#dialog .book-card').count(), 1);
  await close();

  await page.goto(base + '/#tasks');
  await page.locator('[data-action="new-task"]').first().click();
  await page.locator('#f-title').fill('Draft survives a reload');
  await page.locator('.task-details summary').click();
  await page.locator('#task-description').fill('Keep this unfinished note.');
  await page.keyboard.press('Escape');
  await page.reload();
  await page.locator('[data-action="new-task"]').first().click();
  await page.waitForFunction(() => document.querySelector('#f-title')?.value === 'Draft survives a reload');
  assert.equal(await page.locator('#task-description').inputValue(), 'Keep this unfinished note.');
  await save();
  const draftTask = app.getState().tasks.find(task => task.title === 'Draft survives a reload');
  assert.ok(draftTask);

  await page.locator('[data-action="new-task"]').first().click();
  await page.locator('#f-title').fill('MWF habit');
  await page.locator('.task-details summary').click();
  await page.locator('#f-repeat').selectOption('weekdays');
  for (const checkbox of await page.locator('#habit-weekdays input').all()) await checkbox.uncheck();
  for (const day of [1, 3, 5]) await page.locator(`#habit-weekdays input[value="${day}"]`).check();
  await save();
  const scheduled = app.getState().tasks.find(task => task.title === 'MWF habit');
  assert.equal(isDue(scheduled, '2026-11-24'), false);
  await page.locator('[data-action="new-task"]').first().click();
  await page.locator('#f-title').fill('Weekly quota');
  await page.locator('.task-details summary').click();
  await page.locator('#f-repeat').selectOption('quota');
  await page.locator('#f-weeklyTarget').fill('3');
  await save();
  assert.equal(app.getState().tasks.find(task => task.title === 'Weekly quota').weeklyTarget, 3);

  await page.goto(base + '/#projects');
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.locator('#f-title').fill('A reading project');
  await page.locator('#f-outcome').fill('Finish the reading list');
  await save();
  assert.equal(app.getState().projects[0].outcome, 'Finish the reading list');
  await page.goto(base + '/#tasks');
  await page.locator('.task-title').filter({ hasText: 'Draft survives a reload' }).click();
  await page.locator('#f-projectId').selectOption(app.getState().projects[0].id);
  await page.locator('#f-workStatus').selectOption('waiting');
  await page.locator('#f-waitingFor').fill('A library reservation');
  await save();
  await page.goto(base + '/#projects');
  await page.locator('.project-card summary').click();
  assert.ok((await page.locator('.project-card').innerText()).includes('A library reservation'));

  await page.goto(base + '/#life');
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  await context.setOffline(true);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('[data-action="book-log"]').first().click();
  await page.locator('#f-page').fill('25');
  await save();
  assert.equal(app.getState().reading.books[0].currentPage, 20);
  assert.match(await page.locator('.book-position').first().innerText(), /25/);
  await page.goto(base + '/#tasks', { waitUntil: 'domcontentloaded' });
  await page.locator('#task-search').fill(offlineTask.title);
  await page.locator('.task-row .checkbox').click();
  await page.goto(base + '/#focus', { waitUntil: 'domcontentloaded' });
  await page.locator('[data-action="start"]').click();
  await page.locator('[data-action="pause"]').waitFor();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('episuite.snapshot')).timer.local), true);
  await page.locator('[data-action="finish"]').click();
  await page.locator('[data-action="start"]').waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  assert.ok((await page.locator('#main').innerText()).includes('waiting to sync'));
  await context.setOffline(false);
  await page.evaluate(() => window.dispatchEvent(new Event('online')));
  await waitForCondition(() => app.getState().reading.books[0].currentPage === 25 && app.getState().tasks.find(task => task.id === offlineTask.id).completed && app.getState().sessions.length === 1);

  await page.goto(base + '/#settings');
  await page.locator('#settings-section').selectOption('data');
  await page.getByRole('button', { name: 'Manage automatic backups', exact: true }).click();
  await page.getByRole('button', { name: 'Back up now', exact: true }).click();
  await page.getByRole('button', { name: 'Check backup', exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Check backup', exact: true }).first().click();
  await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('Integrity and restore format checked'));
  await close();
  await page.goto(base + '/#life');
  await page.locator('#main').focus();
  const out = fileURLToPath(new URL('../test-results/', import.meta.url));
  await mkdir(out, { recursive: true });
  await page.screenshot({ path: path.join(out, 'review-features-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(out, 'review-features-phone.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Review-feature browser checks passed: history, cover replacement, library search, drafts, schedules, projects, offline activity, and backups');
} finally {
  await browser?.close(); await app?.close();
  assert.ok(path.resolve(directory).startsWith(path.resolve(tmpdir()) + path.sep + 'episuite-review-browser-'));
  await rm(directory, { recursive: true, force: true });
}
